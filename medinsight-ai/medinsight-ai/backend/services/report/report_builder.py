"""
MedInsight AI — Report Builder Service.
Assembles the complete 16-section MedicalReport from normalized patient records,
analysis engine outputs, document processing summaries, and verified citations.
"""

import datetime
import logging
import uuid
from typing import Any, Optional

from api.models import (
    Citation,
    DocumentProcessingSummary,
    ExtractedDocument,
    MedicalReport,
    PatientRecord,
    RiskCategory,
    RiskItem,
    TimelineEvent,
    TreatmentOption,
    TrendObservation,
)
from services.report.report_schema import validate_medical_report

logger = logging.getLogger("medinsight.report.builder")

DEFAULT_DISCLAIMER = (
    "IMPORTANT: This report is generated by an AI system for informational and educational "
    "purposes only. It is NOT a medical diagnosis, prescription, or treatment plan. "
    "This report does NOT replace professional medical advice, diagnosis, or treatment. "
    "Always consult a qualified healthcare professional for medical decisions. "
    "The AI may make errors in text extraction, interpretation, or analysis. "
    "Verify all findings with your treating physician."
)


class ReportBuilder:
    """Constructs and validates the unified 16-section MedicalReport."""

    def __init__(self):
        pass

    def _build_patient_overview(self, record: PatientRecord) -> dict[str, Any]:
        """Construct Section 2 overview dictionary."""
        return {
            "patient_id": record.patient_id or "Not documented",
            "name": record.name or "De-identified Patient",
            "age": record.age or "Unspecified",
            "sex": record.sex or "Unspecified",
            "blood_group": record.blood_group or "Not documented",
            "total_diagnoses": len(record.diagnoses),
            "active_medications": len([m for m in record.medications if m.status.lower() == "active"]) or len(record.medications),
            "abnormal_labs_count": len([l for l in record.lab_results if l.is_abnormal]),
            "documented_allergies_count": len(record.allergies),
            "date_range": record.date_range or "Not specified",
        }

    def _build_document_processing(
        self, extracted_docs: Optional[list[ExtractedDocument]]
    ) -> list[DocumentProcessingSummary]:
        """Construct Section 3 document summaries."""
        summaries: list[DocumentProcessingSummary] = []
        if not extracted_docs:
            return summaries

        for doc in extracted_docs:
            method = "digital"
            ocr_conf = "high"
            if doc.pages:
                method = doc.pages[0].extraction_method
                ocr_conf = str(doc.pages[0].ocr_confidence.value if hasattr(doc.pages[0].ocr_confidence, "value") else doc.pages[0].ocr_confidence)

            summaries.append(
                DocumentProcessingSummary(
                    filename=doc.filename,
                    file_type=doc.file_type.value if hasattr(doc.file_type, "value") else str(doc.file_type),
                    pages_processed=doc.total_pages or len(doc.pages),
                    extraction_method=method,
                    ocr_confidence=ocr_conf,
                    warnings=doc.extraction_warnings,
                )
            )
        return summaries

    def _build_existing_conditions(self, record: PatientRecord) -> list[dict[str, Any]]:
        """Construct Section 5 existing conditions list."""
        conditions: list[dict[str, Any]] = []
        for d in record.diagnoses:
            conditions.append({
                "condition": d.condition,
                "icd_code": d.icd_code or "",
                "status": d.status or "active",
                "date": d.date.original if d.date else "",
                "notes": d.notes or "",
                "source_document": d.source.document_name or "",
            })
        return conditions

    def _build_lab_results(self, record: PatientRecord) -> list[dict[str, Any]]:
        """Construct Section 6 lab results list."""
        labs: list[dict[str, Any]] = []
        for l in record.lab_results:
            labs.append({
                "test_name": l.test_name,
                "value": l.value,
                "unit": l.unit,
                "reference_range": l.reference_range or "Not provided",
                "is_abnormal": bool(l.is_abnormal),
                "date": l.date.original if l.date else "",
                "notes": l.notes or "",
                "source_document": l.source.document_name or "",
            })
        return labs

    def build_report(
        self,
        analysis_id: str,
        record: PatientRecord,
        stage_outputs: dict[str, Any],
        extracted_docs: Optional[list[ExtractedDocument]] = None,
    ) -> MedicalReport:
        """
        Assemble the complete 16-section MedicalReport.
        """
        report_id = f"REP-{uuid.uuid4().hex[:8].upper()}"
        generated_at = datetime.datetime.now().isoformat()

        # Build individual sections
        executive_summary = stage_outputs.get("executive_summary", "")
        patient_overview = self._build_patient_overview(record)
        document_processing = self._build_document_processing(extracted_docs)
        timeline = stage_outputs.get("timeline", [])
        existing_conditions = self._build_existing_conditions(record)
        lab_results = self._build_lab_results(record)
        patterns_and_trends = stage_outputs.get("patterns_and_trends", [])
        risks = stage_outputs.get("risks", [])
        treatment_options = stage_outputs.get("treatment_options", [])
        medication_review = stage_outputs.get("medication_review", [])
        allergy_flags = stage_outputs.get("allergy_flags", [])
        preventive_care = stage_outputs.get("preventive_care", [])
        missing_information = stage_outputs.get("missing_information", [])
        contradictions = stage_outputs.get("contradictions", [])
        doctor_questions = stage_outputs.get("doctor_questions", [])
        urgent_findings = stage_outputs.get("urgent_findings", [])
        citations = stage_outputs.get("citations", [])
        limitations = stage_outputs.get("limitations", [])

        report = MedicalReport(
            report_id=report_id,
            generated_at=generated_at,
            analysis_id=analysis_id,
            executive_summary=executive_summary,
            patient_overview=patient_overview,
            document_processing=document_processing,
            timeline=timeline,
            existing_conditions=existing_conditions,
            lab_results=lab_results,
            patterns_and_trends=patterns_and_trends,
            risks=risks,
            treatment_options=treatment_options,
            medication_review=medication_review,
            allergy_flags=allergy_flags,
            preventive_care=preventive_care,
            missing_information=missing_information,
            contradictions=contradictions,
            doctor_questions=doctor_questions,
            urgent_findings=urgent_findings,
            citations=citations,
            limitations=limitations,
            disclaimer=DEFAULT_DISCLAIMER,
        )

        # Validate completeness and safety
        issues = validate_medical_report(report)
        if issues:
            logger.warning(f"Report validation warnings for {report_id}: {issues}")
        else:
            logger.info(f"Report {report_id} passed all 16 section validations.")

        return report


# Global singleton instance
report_builder = ReportBuilder()
